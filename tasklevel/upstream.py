"""Upstream comparison: measure each external design at its native interface (Table 3).

The five externally derived benchmarks ship a `benchmarks/upstream/<name>/` measurement benchmark:
the verbatim upstream RTL (marked edits only) driven over its native interface by a testbench that
replays the study workload and counts cycles. Each is synthesized through the study flow over a
small target-delay sweep (500 ps, then +/-20% of the achieved period, then their mean) and the
lowest-arp point is reported, next to the recast start and the task-level winner of the Spire runs.

    python -m tasklevel.upstream                 # sweep (resumable) + table from the manifest's arp runs
    python -m tasklevel.upstream --sweep-only

Outputs: data/upstream_evals.json (sweep), data/analysis/table_upstream.{tex,md}.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import common as U
from . import config as C
from .benches import BENCHES

RESULTS = C.DATA / "upstream_evals.json"


def run_eval(bench_dir: Path, target: float) -> dict:
    sp = json.loads((bench_dir / "metadata.json").read_text())["starting_point"]
    log = C.DATA / "logs" / f"upstream_{bench_dir.name}_{target:.0f}.log"
    cmd = [C.PYTHON, "-m", "rtlscout.run_eval", str(bench_dir / sp), "--benchmark", str(bench_dir),
           "--cost-metric", "area_runtime_product", "--skip-netlist-sim", "--target-delay", str(target),
           "--technology", "asap7", "--json"]
    U.sh(cmd, log, check=False)
    t = log.read_text()
    j = json.loads(t[t.index("{"):])
    if not j.get("passed"):
        raise RuntimeError(f"upstream eval failed for {bench_dir.name} @ {target}: see {log}")
    m = j["metrics"]
    return dict(target=target, area=m["area"], delay=m["delay"], cycles=m["cycles"],
                adp=m["area"] * m["cycles"] * m["delay"])


def sweep(name: str) -> dict:
    bench_dir = C.UPSTREAM_BENCHMARKS / name
    allr = json.loads(RESULTS.read_text()) if RESULTS.exists() else {}
    rec = allr.get(name, {})

    def get(point, target):
        if point not in rec:
            rec[point] = run_eval(bench_dir, round(target, 1))
            allr[name] = rec
            U.write_json_atomic(RESULTS, allr)
            r = rec[point]
            U.log(f"upstream {name} {point}: target={r['target']:.0f} area={r['area']:.0f} delay={r['delay']:.0f} arp={r['adp']:.3g}")
        return rec[point]
    base = get("base", 500.0)
    hi = get("hi", base["delay"] * 1.2)
    lo = get("lo", base["delay"] * 0.8)
    get("mid", (hi["delay"] + lo["delay"]) / 2)
    return rec


def _sci(v):
    mant, ex = ("%.2e" % v).split("e")
    e = int(ex)
    return f"${mant}{{\\times}}10^{{{e if e >= 10 else f'{e}\\phantom{{1}}'}}}$"


def table(upstream: dict, out_dir: Path) -> None:
    """Table 3 from the manifest's arp runs (Spire, task-level winner = best validated repetition)."""
    from .analysis._common import cells_for
    cells = cells_for(["arp"], hdl="spire")
    tex = ["% generated by tasklevel.upstream -- do not hand-edit", "\\begin{tabular}{lrrrr}", "\\toprule",
           " & upstream & start & task-level & task / upstream \\\\", "\\midrule"]
    md = ["| benchmark | upstream | start | task-level | task / upstream |", "|---|---|---|---|---|"]
    for b in BENCHES:
        c = cells.get((b.key, "task"))
        if c is None:
            continue
        start, task = c["start_arp"], c["best_arp"]
        if b.upstream is None or b.upstream not in upstream:
            tex.append(f"{b.tex}$^{{\\ast}}$ & --- & {_sci(start)} & {_sci(task)} & --- \\\\")
            md.append(f"| {b.label} | --- | {start:.3g} | {task:.3g} | --- |")
            continue
        best = min(upstream[b.upstream].values(), key=lambda r: r["adp"])
        tex.append(f"{b.tex} & {_sci(best['adp'])} & {_sci(start)} & {_sci(task)} & \\textbf{{{task / best['adp']:.2f}}} \\\\")
        md.append(f"| {b.label} | {best['adp']:.3g} (area {best['area']:.0f}, delay {best['delay']:.0f}, cycles {best['cycles']:.0f}) | "
                  f"{start:.3g} | {task:.3g} | {task / best['adp']:.2f} |")
    tex += ["\\bottomrule", "\\end{tabular}"]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "table_upstream.tex").write_text("\n".join(tex) + "\n")
    (out_dir / "table_upstream.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sweep-only", action="store_true")
    a = ap.parse_args()
    (C.DATA / "logs").mkdir(parents=True, exist_ok=True)
    res = {}
    for b in BENCHES:
        if b.upstream:
            res[b.upstream] = sweep(b.upstream)
    if not a.sweep_only:
        table(res, C.DATA / "analysis")


if __name__ == "__main__":
    main()
