// Testbench for jpeg_idct_2d_upstream: the FULL verbatim core_jpeg 2-D IDCT
// (jpeg_idct top incl. its own jpeg_idct_ram input stage) driven over the
// upstream's REAL ingress: ONE 16-bit coefficient per cycle with 6-bit idx,
// eob on the last, and inport_accept_o backpressure honored. Outputs are the
// streamed 32-bit pixels with row-major outport_idx_o.
//
// Metering mirrors the study TBs (fairness: the 1r1w spire TB resets between
// cases and sums per-case cycles, so no design gets cross-block pipelining
// credit): reset between blocks, per-block cycles counted from reset release
// to the 64th output, summed into TB_CYCLES.
//
// Workload: vectors.dat identical to jpeg_idct_2d_verilog (one line per
// block: 64 coefficients, 4-hex signed, row-major, then 64 expected outputs,
// 8-hex; goldens were generated by this same upstream RTL).
module tb;
  int total_checks;
  int total_errors;
  int cyc_total;

  logic        clk;
  logic        rst;
  logic        img_start;
  logic        inport_valid;
  logic [15:0] inport_data;
  logic [5:0]  inport_idx;
  logic        inport_eob;
  logic        inport_accept;
  logic        outport_valid;
  logic [31:0] outport_data;
  logic [5:0]  outport_idx;

  jpeg_idct_2d_upstream dut (
    .clk(clk), .rst(rst),
    .img_start_i(img_start), .img_end_i(1'b0),
    .inport_valid_i(inport_valid),
    .inport_data_i(inport_data),
    .inport_idx_i(inport_idx),
    .inport_eob_i(inport_eob),
    .outport_accept_i(1'b1),
    .inport_accept_o(inport_accept),
    .outport_valid_o(outport_valid),
    .outport_data_o(outport_data),
    .outport_idx_o(outport_idx)
  );

  initial clk = 1'b0;
  always #5 clk = ~clk;

  // ---- load vectors.dat: flat token stream, 128 tokens per block ----------
  localparam MAX_BLOCKS = 1024;
  logic [15:0] coeffs [0:MAX_BLOCKS*64-1];
  logic [31:0] expy   [0:MAX_BLOCKS*64-1];
  int num_blocks;

  task automatic load_vectors;
    int fd, rc, n;
    logic [31:0] tok;
    fd = $fopen("vectors.dat", "r");
    if (fd == 0) begin
      $display("ERROR: cannot open vectors.dat");
      $fatal(1, "FAIL");
    end
    n = 0;
    rc = $fscanf(fd, "%h", tok);
    while (rc == 1) begin
      if ((n % 128) < 64) coeffs[(n/128)*64 + (n%128)] = tok[15:0];
      else                expy[(n/128)*64 + (n%128) - 64] = tok;
      n = n + 1;
      rc = $fscanf(fd, "%h", tok);
    end
    $fclose(fd);
    num_blocks = n / 128;
    $display("Loaded %0d blocks", num_blocks);
  endtask

  int out_cnt;                  // outputs seen in the current block

  always @(posedge clk) begin
    if (!rst && outport_valid) begin
      total_checks = total_checks + 1;
      if (outport_data !== expy[blk_base + outport_idx]) begin
        total_errors = total_errors + 1;
        if (total_errors <= 10)
          $display("MISMATCH blk %0d idx %0d: got %08x exp %08x",
                   blk_base / 64, outport_idx, outport_data,
                   expy[blk_base + outport_idx]);
      end
      out_cnt = out_cnt + 1;
    end
  end

  int blk_base;

  task automatic run_block(input int b);
    int k, cyc;
    begin
      blk_base = b * 64;

      // reset between blocks (not counted), like the study TBs
      inport_valid = 1'b0;
      inport_data = '0;
      inport_idx = '0;
      inport_eob = 1'b0;
      img_start = 1'b0;
      rst = 1'b1;
      @(negedge clk); @(negedge clk);
      rst = 1'b0;
      out_cnt = 0;
      cyc = 0;

      // image-start pulse (each block is a fresh image after reset)
      img_start = 1'b1;
      @(negedge clk); cyc = cyc + 1;
      img_start = 1'b0;

      // real ingress: one coefficient per cycle, accept-gated
      k = 0;
      while (k < 64) begin
        inport_valid = 1'b1;
        inport_data = coeffs[blk_base + k];
        inport_idx = k[5:0];
        inport_eob = (k == 63);
        @(posedge clk);
        cyc = cyc + 1;
        if (inport_accept) k = k + 1;
        if (cyc > 2000) begin
          $display("TB_CYCLES total=%0d", cyc_total + cyc);
          $display("TB_SUMMARY total=%0d errors=%0d", total_checks + 1, total_errors + 1);
          $fatal(1, "WATCHDOG: block %0d stuck feeding at k=%0d", b, k);
        end
        @(negedge clk);
      end
      inport_valid = 1'b0;
      inport_eob = 1'b0;

      // wait for all 64 outputs of this block
      while (out_cnt < 64) begin
        @(posedge clk);
        cyc = cyc + 1;
        if (cyc > 2000) begin
          $display("TB_CYCLES total=%0d", cyc_total + cyc);
          $display("TB_SUMMARY total=%0d errors=%0d", total_checks + 1, total_errors + 1);
          $fatal(1, "WATCHDOG: block %0d only %0d outputs after %0d cycles", b, out_cnt, cyc);
        end
        @(negedge clk);
      end
      cyc_total = cyc_total + cyc;
      // live cross-process read of the check counters: works around the
      // simulator const-folding issue (counters read only at end-of-sim
      // fold to 0; same workaround as the 1r1w study TBs)
      if (b % 100 == 0)
        $display("TRACE blk %0d checks=%0d errors=%0d", b, total_checks, total_errors);
    end
  endtask

  initial begin
    total_checks = 0;
    total_errors = 0;
    cyc_total = 0;
    out_cnt = 0;
    blk_base = 0;
    rst = 1'b1;
    img_start = 1'b0;
    inport_valid = 1'b0;
    inport_data = '0;
    inport_idx = '0;
    inport_eob = 1'b0;

    load_vectors();

    for (int b = 0; b < num_blocks; b++) begin
      run_block(b);
    end

    $display("TB_CYCLES total=%0d", cyc_total);
    $display("TB_SUMMARY total=%0d errors=%0d", total_checks, total_errors);
    if (total_errors != 0) $fatal(1, "FAIL");
    $display("PASS");
    $finish;
  end

`ifdef VCD_FILE_PATH
// VCD dump of the DUT subtree for measured-power evaluation: tech_eval's
// netlist sim passes -DVCD_FILE_PATH=<path> + --trace-vcd; inert otherwise.
`define __PWRSTR(x) `"x`"
  initial begin
    $dumpfile(`__PWRSTR(`VCD_FILE_PATH));
    $dumpvars(0, dut);
  end
`endif
endmodule
